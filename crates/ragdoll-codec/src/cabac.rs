/// A single CABAC context model: `pStateIdx` (`0..=63`) and `valMPS` (`0` or `1`), packed as
/// `2 * state + mps` so that a decision reads and writes one byte.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct CabacContext(u8);

impl CabacContext {
    /// The context with probability state `state` (`0..=63`) and most probable symbol `mps`.
    #[inline]
    pub fn new(state: u8, mps: u8) -> Self {
        Self(((state & 63) << 1) | (mps & 1))
    }

    /// `pStateIdx`, `0..=63`.
    #[inline]
    pub fn state(self) -> u8 {
        self.0 >> 1
    }

    /// `valMPS`, `0` or `1`.
    #[inline]
    pub fn mps(self) -> u8 {
        self.0 & 1
    }

    /// Initializes a context model from `(m, n)` slope/offset parameters and `slice_qp` (`0..=51`)
    /// per ITU-T H.264 9.3.1.1.
    #[inline]
    pub fn from_mn_qp(m: i8, n: i8, slice_qp: u8) -> Self {
        let pre_ctx_state =
            (((m as i32 * (slice_qp.min(51) as i32)) >> 4) + (n as i32)).clamp(1, 126);
        if pre_ctx_state <= 63 {
            Self::new((63 - pre_ctx_state) as u8, 0)
        } else {
            Self::new((pre_ctx_state - 64) as u8, 1)
        }
    }
}

/// The decoder's tables in one array, so that a decision needs a single base address:
///
/// - `[0, 512)`: the left shift that renormalises a range `r` (`2..=510`) to `256..=511`,
///   indexed by `r`;
/// - `[DEC_LPS, +512)`: `rangeTabLPS` (Table 9-44) indexed by `qCodIRangeIdx << 7 | packed
///   context`, where packed values above 127 are never read;
/// - `[DEC_NEXT, +256)`: the packed context after a decision (Table 9-45), indexed by the packed
///   context after an MPS and by its complement `255 - context` after an LPS, so that the
///   index's low bit is the decoded bin either way.
static DEC_TAB: [u8; 1280] = {
    let mut t = [0u8; 1280];
    let mut r = 1;
    while r < 512 {
        t[r] = ((r as u32).leading_zeros() - 23) as u8;
        r += 1;
    }
    let mut i = 0;
    while i < 512 {
        let (q, s) = (i >> 7, i & 127);
        t[DEC_LPS + i] = CABAC_RANGE_TAB_LPS[s >> 1][q];
        i += 1;
    }
    let mut s = 0;
    while s < 128 {
        let (st, mps) = (s >> 1, (s & 1) as u8);
        t[DEC_NEXT + s] = (CABAC_TRANS_IDX_MPS[st] << 1) | mps;
        t[DEC_NEXT + 255 - s] = (CABAC_TRANS_IDX_LPS[st] << 1) | (mps ^ (st == 0) as u8);
        s += 1;
    }
    t
};
const DEC_LPS: usize = 512;
const DEC_NEXT: usize = 1024;

/// Standard 460-context CABAC context bank for H.264 Main/High 4:2:0 slice syntax and DCT residuals.
pub const NUM_CABAC_CONTEXTS: usize = 460;

/// Initializes the 460-entry CABAC context bank for a given `slice_qp` (`0..=51`), slice type,
/// and `cabac_init_idc` (`0..=2`) using ITU-T H.264 Table 9-12..9-33.
pub fn init_cabac_contexts(
    slice_qp: u8,
    is_intra_slice: bool,
    cabac_init_idc: u8,
) -> [CabacContext; NUM_CABAC_CONTEXTS] {
    let table_idx = if is_intra_slice {
        0
    } else {
        1 + (cabac_init_idc.min(2) as usize)
    };
    let mut ctxs = [CabacContext::default(); NUM_CABAC_CONTEXTS];
    for (slot, &(m, n)) in ctxs.iter_mut().zip(CABAC_CONTEXT_INIT[table_idx].iter()) {
        *slot = CabacContext::from_mn_qp(m, n, slice_qp);
    }
    ctxs
}

/// ITU-T H.264 9.3.3.2 CABAC Binary Arithmetic Encoder (`M`-Coder, `x264` bit-exact state machine).
#[derive(Clone, Debug)]
pub struct CabacEncoder {
    pub low: u32,
    pub range: u32,
    pub queue: i32,
    pub bytes_outstanding: u32,
    pub out: Vec<u8>,
}

impl CabacEncoder {
    pub fn new() -> Self {
        Self {
            low: 0,
            range: 510,
            queue: -9,
            bytes_outstanding: 0,
            out: Vec::with_capacity(1024),
        }
    }

    #[inline]
    fn putbyte(&mut self) {
        if self.queue >= 0 {
            let out = self.low >> (self.queue + 10);
            self.low &= (0x400u32 << self.queue) - 1;
            self.queue -= 8;
            if (out & 0xFF) == 0xFF {
                self.bytes_outstanding += 1;
            } else {
                let carry = out >> 8;
                if let Some(last) = self.out.last_mut() {
                    *last = last.wrapping_add(carry as u8);
                }
                let fill = if carry != 0 { 0x00u8 } else { 0xFFu8 };
                while self.bytes_outstanding > 0 {
                    self.out.push(fill);
                    self.bytes_outstanding -= 1;
                }
                self.out.push((out & 0xFF) as u8);
            }
        }
    }

    #[inline]
    fn renormalize(&mut self) {
        while self.range < 256 {
            self.range <<= 1;
            self.low <<= 1;
            self.queue += 1;
            if self.queue >= 0 {
                self.putbyte();
            }
        }
    }

    /// Encodes a single binary decision `bin` (`0` or `1`) using `ctx` (ITU-T H.264 9.3.3.2.1).
    #[inline]
    pub fn encode_decision(&mut self, ctx: &mut CabacContext, bin: u8) {
        let b = bin & 1;
        let q_idx = ((self.range >> 6) & 3) as usize;
        let st = ctx.state() as usize;
        let r_lps = CABAC_RANGE_TAB_LPS[st][q_idx] as u32;
        self.range -= r_lps;

        if b != ctx.mps() {
            self.low += self.range;
            self.range = r_lps;
            *ctx = CabacContext::new(CABAC_TRANS_IDX_LPS[st], ctx.mps() ^ (st == 0) as u8);
        } else {
            *ctx = CabacContext::new(CABAC_TRANS_IDX_MPS[st], ctx.mps());
        }
        self.renormalize();
    }

    /// Encodes an equiprobable bypass bin (`0` or `1`, ITU-T H.264 9.3.3.2.3).
    #[inline]
    pub fn encode_bypass(&mut self, bin: u8) {
        self.low <<= 1;
        if (bin & 1) != 0 {
            self.low += self.range;
        }
        self.queue += 1;
        if self.queue >= 0 {
            self.putbyte();
        }
    }

    /// Encodes a terminate bin (`0` = continue, `1` = flush slice, ITU-T H.264 9.3.3.2.4).
    #[inline]
    pub fn encode_terminate(&mut self, bin: u8) {
        self.range -= 2;
        if (bin & 1) != 0 {
            self.low += self.range;
            self.low = (self.low << 9) | 0x200;
            self.queue += 9;
            self.putbyte();
            self.putbyte();
            self.low <<= -self.queue;
            self.queue = 0;
            self.putbyte();
            while self.bytes_outstanding > 0 {
                self.out.push(0xFF);
                self.bytes_outstanding -= 1;
            }
        } else {
            self.renormalize();
        }
    }

    /// Encodes `mb_skip_flag` in a P-slice (`ctx 11..13`, where `cond_a / cond_b = 1` when neighbor is available and NOT skipped).
    #[inline]
    pub fn encode_p_skip(
        &mut self,
        ctxs: &mut [CabacContext],
        cond_a: u8,
        cond_b: u8,
        is_skip: bool,
    ) {
        let ctx_idx = 11 + ((cond_a + cond_b) as usize);
        self.encode_decision(&mut ctxs[ctx_idx], u8::from(is_skip));
    }

    /// Appends a raw `I_PCM` byte to the byte-aligned output stream.
    #[inline]
    pub fn write_raw_byte(&mut self, b: u8) {
        self.out.push(b);
    }

    /// Re-initializes the CABAC arithmetic encoder after an `I_PCM` macroblock (ITU-T H.264 9.3.1.2).
    #[inline]
    pub fn reinit_after_pcm(&mut self) {
        self.low = 0;
        self.range = 510;
        self.queue = -9;
        self.bytes_outstanding = 0;
    }

    /// Returns the number of output bytes emitted so far.
    #[inline]
    pub fn bytes_written(&self) -> usize {
        self.out.len()
    }

    /// Consumes the encoder and returns the encoded CABAC byte vector.
    #[inline]
    pub fn finish(self) -> Vec<u8> {
        self.out
    }

    /// Encodes an I-slice `mb_type` (`0 = I_NxN`, `1..=24 = I_16x16`, `25 = I_PCM`) with `ctx_base` (`3` in I-slice, `17` in P-slice).
    pub fn encode_intra_mb_type(
        &mut self,
        ctxs: &mut [CabacContext],
        ctx_base: usize,
        cond_a: u8,
        cond_b: u8,
        intra_mb_type: u32,
    ) {
        let is_i_slice = ctx_base == 3;
        let c0 = if is_i_slice {
            3 + ((cond_a + cond_b) as usize)
        } else {
            ctx_base
        };
        if intra_mb_type == 0 {
            self.encode_decision(&mut ctxs[c0], 0);
            return;
        }
        self.encode_decision(&mut ctxs[c0], 1);
        if intra_mb_type == 25 {
            self.encode_terminate(1);
            return;
        }
        self.encode_terminate(0);
        let code = intra_mb_type - 1;
        let luma_mode = (code % 4) as u8;
        let cbp_chroma = ((code / 4) % 3) as u8;
        let cbp_luma_nz = u8::from(code >= 12);

        if is_i_slice {
            self.encode_decision(&mut ctxs[6], cbp_luma_nz);
            self.encode_decision(&mut ctxs[7], u8::from(cbp_chroma > 0));
            if cbp_chroma > 0 {
                self.encode_decision(&mut ctxs[8], u8::from(cbp_chroma == 2));
            }
            self.encode_decision(&mut ctxs[9], (luma_mode >> 1) & 1);
            self.encode_decision(&mut ctxs[10], luma_mode & 1);
        } else {
            self.encode_decision(&mut ctxs[ctx_base + 1], cbp_luma_nz);
            self.encode_decision(&mut ctxs[ctx_base + 2], u8::from(cbp_chroma > 0));
            if cbp_chroma > 0 {
                self.encode_decision(&mut ctxs[ctx_base + 2], u8::from(cbp_chroma == 2));
            }
            self.encode_decision(&mut ctxs[ctx_base + 3], (luma_mode >> 1) & 1);
            self.encode_decision(&mut ctxs[ctx_base + 3], luma_mode & 1);
        }
    }

    /// Encodes a P-slice `mb_type` (`0 = P_L0_16x16`, `1 = 16x8`, `2 = 8x16`, `3 = P_8x8`, `>= 5 = Intra`).
    pub fn encode_p_mb_type(&mut self, ctxs: &mut [CabacContext], mb_type: u32) {
        if mb_type >= 5 {
            self.encode_decision(&mut ctxs[14], 1);
            self.encode_intra_mb_type(ctxs, 17, 0, 0, mb_type - 5);
            return;
        }
        self.encode_decision(&mut ctxs[14], 0);
        match mb_type {
            0 => {
                // P_L0_16x16: 0, 0
                self.encode_decision(&mut ctxs[15], 0);
                self.encode_decision(&mut ctxs[16], 0);
            }
            3 | 4 => {
                // P_8x8: 0, 1
                self.encode_decision(&mut ctxs[15], 0);
                self.encode_decision(&mut ctxs[16], 1);
            }
            2 => {
                // P_L0_L0_8x16: 1, 0
                self.encode_decision(&mut ctxs[15], 1);
                self.encode_decision(&mut ctxs[17], 0);
            }
            _ => {
                // P_L0_L0_16x8: 1, 1
                self.encode_decision(&mut ctxs[15], 1);
                self.encode_decision(&mut ctxs[17], 1);
            }
        }
    }

    /// Encodes `prev_intra4x4_pred_mode_flag` (`ctx 68`) and `rem_intra4x4_pred_mode` (`ctx 69`, 3 LSB-first bits).
    pub fn encode_intra4x4_pred_mode(
        &mut self,
        ctxs: &mut [CabacContext],
        prev_flag: bool,
        rem: u8,
    ) {
        if prev_flag {
            self.encode_decision(&mut ctxs[68], 1);
        } else {
            self.encode_decision(&mut ctxs[68], 0);
            self.encode_decision(&mut ctxs[69], rem & 1);
            self.encode_decision(&mut ctxs[69], (rem >> 1) & 1);
            self.encode_decision(&mut ctxs[69], (rem >> 2) & 1);
        }
    }

    /// Encodes `intra_chroma_pred_mode` (`0..=3`, `ctx 64..67`).
    pub fn encode_chroma_pred_mode(
        &mut self,
        ctxs: &mut [CabacContext],
        cond_a: u8,
        cond_b: u8,
        mode: u8,
    ) {
        let c0 = 64 + ((cond_a + cond_b) as usize);
        if mode == 0 {
            self.encode_decision(&mut ctxs[c0], 0);
        } else {
            self.encode_decision(&mut ctxs[c0], 1);
            if mode == 1 {
                self.encode_decision(&mut ctxs[67], 0);
            } else {
                self.encode_decision(&mut ctxs[67], 1);
                self.encode_decision(&mut ctxs[67], u8::from(mode >= 3));
            }
        }
    }

    /// Encodes 1 bit of `coded_block_pattern` luma (`ctx 73..76`, where `cond_a / cond_b` is `1` when neighbor $8\times8$ block has `cbp_bit == 0` or is unavailable).
    #[inline]
    pub fn encode_cbp_luma_bit(
        &mut self,
        ctxs: &mut [CabacContext],
        cond_a: u8,
        cond_b: u8,
        bit: u8,
    ) {
        let ctx_idx = 73 + ((cond_a + 2 * cond_b) as usize);
        self.encode_decision(&mut ctxs[ctx_idx], bit & 1);
    }

    /// Encodes `coded_block_pattern` chroma (`0..=2`, `ctx 77..84`).
    pub fn encode_cbp_chroma(
        &mut self,
        ctxs: &mut [CabacContext],
        chroma_a: u8,
        chroma_b: u8,
        cbp_chroma: u8,
    ) {
        let ca0 = usize::from(chroma_a != 0);
        let cb0 = usize::from(chroma_b != 0);
        if cbp_chroma == 0 {
            self.encode_decision(&mut ctxs[77 + ca0 + 2 * cb0], 0);
        } else {
            self.encode_decision(&mut ctxs[77 + ca0 + 2 * cb0], 1);
            let ca1 = usize::from(chroma_a == 2);
            let cb1 = usize::from(chroma_b == 2);
            self.encode_decision(&mut ctxs[81 + ca1 + 2 * cb1], u8::from(cbp_chroma == 2));
        }
    }

    /// Encodes `mb_qp_delta` (`ctx 60..63`, ITU-T H.264 9.3.2.7).
    pub fn encode_mb_qp_delta(&mut self, ctxs: &mut [CabacContext], prev_nz: u8, delta: i32) {
        let c0 = 60 + usize::from(prev_nz != 0);
        if delta == 0 {
            self.encode_decision(&mut ctxs[c0], 0);
            return;
        }
        let code = if delta > 0 {
            (2 * delta - 1) as u32
        } else {
            (-2 * delta) as u32
        };
        self.encode_decision(&mut ctxs[c0], 1);
        if code == 1 {
            self.encode_decision(&mut ctxs[62], 0);
            return;
        }
        self.encode_decision(&mut ctxs[62], 1);
        for _ in 2..code {
            self.encode_decision(&mut ctxs[63], 1);
        }
        self.encode_decision(&mut ctxs[63], 0);
    }

    /// Encodes `ref_idx_l0` / `ref_idx_l1` (`ctx 54..59`).
    pub fn encode_ref_idx(
        &mut self,
        ctxs: &mut [CabacContext],
        cond_a: u8,
        cond_b: u8,
        ref_idx: u8,
    ) {
        let c0 = 54 + ((cond_a + 2 * cond_b) as usize);
        if ref_idx == 0 {
            self.encode_decision(&mut ctxs[c0], 0);
            return;
        }
        self.encode_decision(&mut ctxs[c0], 1);
        if ref_idx == 1 {
            self.encode_decision(&mut ctxs[58], 0);
            return;
        }
        self.encode_decision(&mut ctxs[58], 1);
        for _ in 2..ref_idx {
            self.encode_decision(&mut ctxs[59], 1);
        }
        self.encode_decision(&mut ctxs[59], 0);
    }

    /// Encodes `mvd_l0[comp]` or `mvd_l1[comp]` (`comp = 0` for x, `1` for y; `ctx 40..53`).
    pub fn encode_mvd(&mut self, ctxs: &mut [CabacContext], comp: usize, abs_sum: u32, mvd: i16) {
        let base = if comp == 0 { 40 } else { 47 };
        let inc0 = if abs_sum < 3 {
            0
        } else if abs_sum <= 32 {
            1
        } else {
            2
        };
        let abs_v = mvd.unsigned_abs() as u32;
        if abs_v == 0 {
            self.encode_decision(&mut ctxs[base + inc0], 0);
            return;
        }
        self.encode_decision(&mut ctxs[base + inc0], 1);
        let prefix = abs_v.min(9);
        for i in 1..prefix {
            let c_idx = base + 3 + (i as usize - 1).min(3);
            self.encode_decision(&mut ctxs[c_idx], 1);
        }
        if abs_v < 9 {
            let c_idx = base + 3 + (abs_v as usize - 1).min(3);
            self.encode_decision(&mut ctxs[c_idx], 0);
        } else {
            let mut rem = abs_v - 9;
            let mut k = 3u32;
            while rem >= (1 << k) {
                self.encode_bypass(1);
                rem -= 1 << k;
                k += 1;
            }
            self.encode_bypass(0);
            for bit in (0..k).rev() {
                self.encode_bypass(((rem >> bit) & 1) as u8);
            }
        }
        self.encode_bypass(u8::from(mvd < 0));
    }

    /// Encodes a zig-zag scanned residual block in CABAC category `cat` (`0..=5`) per ITU-T H.264 9.3.3.1.3.
    /// Returns the `coded_block_flag` (`0` or `1`).
    pub fn encode_residual_block_cat(
        &mut self,
        ctxs: &mut [CabacContext],
        cat: usize,
        cbf_cond: u8,
        coeffs: &[i16],
    ) -> u8 {
        const CBF_BASE: [usize; 5] = [85, 89, 93, 97, 101];
        const SIG_BASE: [usize; 6] = [105, 120, 134, 149, 152, 402];
        const LAST_BASE: [usize; 6] = [166, 181, 195, 210, 213, 417];
        const LVL_BASE: [usize; 6] = [227, 237, 247, 257, 266, 426];

        let max_coeff = coeffs.len();
        let last_nz = coeffs.iter().rposition(|&c| c != 0);
        if cat < 5 {
            let cbf_ctx = CBF_BASE[cat] + (cbf_cond as usize);
            let Some(last_idx) = last_nz else {
                self.encode_decision(&mut ctxs[cbf_ctx], 0);
                return 0;
            };
            self.encode_decision(&mut ctxs[cbf_ctx], 1);
            self.encode_sig_and_levels(
                ctxs,
                cat,
                SIG_BASE[cat],
                LAST_BASE[cat],
                LVL_BASE[cat],
                max_coeff,
                last_idx,
                coeffs,
            );
            1
        } else {
            let last_idx = last_nz.unwrap_or(0);
            self.encode_sig_and_levels(
                ctxs,
                5,
                SIG_BASE[5],
                LAST_BASE[5],
                LVL_BASE[5],
                max_coeff,
                last_idx,
                coeffs,
            );
            1
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn encode_sig_and_levels(
        &mut self,
        ctxs: &mut [CabacContext],
        cat: usize,
        sig_base: usize,
        last_base: usize,
        lvl_base: usize,
        max_coeff: usize,
        last_idx: usize,
        coeffs: &[i16],
    ) {
        let mut sig_positions = [0usize; 64];
        let mut sig_count = 0usize;

        for (i, &c) in coeffs.iter().enumerate().take(last_idx + 1) {
            if i < max_coeff - 1 {
                let sig_off = if cat == 5 {
                    SIG_COEFF_OFFSET_8X8[i] as usize
                } else {
                    i
                };
                if c == 0 {
                    self.encode_decision(&mut ctxs[sig_base + sig_off], 0);
                    continue;
                }
                self.encode_decision(&mut ctxs[sig_base + sig_off], 1);
                let last_off = if cat == 5 {
                    LAST_COEFF_OFFSET_8X8[i] as usize
                } else {
                    i
                };
                self.encode_decision(&mut ctxs[last_base + last_off], u8::from(i == last_idx));
            }
            sig_positions[sig_count] = i;
            sig_count += 1;
        }

        let mut num_eq1 = 0usize;
        let mut num_gt1 = 0usize;
        let gt_max = if cat == 3 { 3 } else { 4 };

        for &pos in sig_positions[..sig_count].iter().rev() {
            let c = coeffs[pos];
            let abs_m1 = (c.unsigned_abs() as u32) - 1;
            let c0 = if num_gt1 > 0 { 0 } else { (1 + num_eq1).min(4) };
            if abs_m1 == 0 {
                self.encode_decision(&mut ctxs[lvl_base + c0], 0);
                num_eq1 += 1;
            } else {
                self.encode_decision(&mut ctxs[lvl_base + c0], 1);
                let c1 = 5 + num_gt1.min(gt_max);
                let prefix = abs_m1.min(14);
                for _ in 1..prefix {
                    self.encode_decision(&mut ctxs[lvl_base + c1], 1);
                }
                if abs_m1 < 14 {
                    self.encode_decision(&mut ctxs[lvl_base + c1], 0);
                } else {
                    let mut rem = abs_m1 - 14;
                    let mut k = 0u32;
                    while rem >= (1 << k) {
                        self.encode_bypass(1);
                        rem -= 1 << k;
                        k += 1;
                    }
                    self.encode_bypass(0);
                    for bit in (0..k).rev() {
                        self.encode_bypass(((rem >> bit) & 1) as u8);
                    }
                }
                num_gt1 += 1;
            }
            self.encode_bypass(u8::from(c < 0));
        }
    }

    pub fn into_bytes(self) -> Vec<u8> {
        self.out
    }
}

impl Default for CabacEncoder {
    fn default() -> Self {
        Self::new()
    }
}

/// ITU-T H.264 9.3.1.2 & 9.3.3.2 CABAC Binary Arithmetic Decoder (`M`-Coder).
#[derive(Clone, Debug)]
pub struct CabacDecoder<'a> {
    data: &'a [u8],
    /// Next byte of `data` not yet in `value`.
    pos: usize,
    /// `codIOffset` in the top 10 bits (9 plus headroom for a bypass shift), followed by the
    /// stream's next bits and then a single set marker bit with zeros below it (FFmpeg's
    /// `CABAC_MASK` scheme): the marker's position counts the valid bits, and while it stays in
    /// the low 32 bits at least [`Self::MIN_BITS`] of them remain, so a decision checks for a
    /// refill with one test.
    value: u64,
    range: u32,
}

impl<'a> CabacDecoder<'a> {
    /// Bit position of the offset's least significant bit in `value`.
    const SHIFT: u32 = 54;
    /// Valid bits left when the marker is at bit 31, its highest position between bins: more
    /// than a decision (at most 7, range being at least 6 after an LPS) or a bypass bin consume.
    const MIN_BITS: u32 = Self::SHIFT - 1 - 31;

    /// Initializes a CABAC arithmetic decoder from byte-aligned slice payload `data` (ITU-T H.264 9.3.1.2).
    pub fn new(data: &'a [u8]) -> Result<Self> {
        if data.len() < 2 {
            return Err(RagdollError::BitstreamEndOfData);
        }
        let mut d = Self {
            data,
            pos: 0,
            value: 0,
            range: 510,
        };
        d.start();
        Ok(d)
    }

    /// Loads the 9-bit initial offset from `pos` (9.3.1.2).
    fn start(&mut self) {
        // No valid bits: the marker sits just below the offset.
        self.value = 1 << (Self::SHIFT - 1);
        self.refill();
        self.consume(9);
        self.range = 510;
    }

    /// Fills the bits below the valid ones with whole bytes, leaving the marker in the low byte;
    /// past the end of `data` the stream reads as zeros.
    #[inline(always)]
    fn refill(&mut self) {
        (self.pos, self.value) = Self::refilled(self.data, self.pos, self.value);
    }

    /// [`Self::refill`] on values, so that the decoder state of a caller can stay in registers.
    #[cold]
    #[inline(never)]
    fn refilled(data: &[u8], mut pos: usize, value: u64) -> (usize, u64) {
        let m = value.trailing_zeros();
        // Whole bytes fit above bit 0: the new marker lands at m - 8 * k, in 0..8.
        let k = m / 8;
        debug_assert!(k >= 1 && Self::SHIFT - 1 - (m - 8 * k) >= Self::MIN_BITS);
        let mut value = value ^ (1 << m);
        if let Some(b) = data.get(pos..pos + 8) {
            let v = u64::from_be_bytes(b.try_into().expect("8 bytes"));
            value |= (v >> (64 - 8 * k)) << (m + 1 - 8 * k);
        } else {
            for j in 0..k {
                let b = data.get(pos + j as usize).copied().unwrap_or(0) as u64;
                value |= b << (m + 1 - 8 * (j + 1));
            }
        }
        pos += k as usize;
        (pos, value | 1 << (m - 8 * k))
    }

    /// Shifts `n` stream bits into the offset.
    #[inline(always)]
    fn consume(&mut self, n: u32) {
        self.value <<= n;
        if self.value as u32 == 0 {
            self.refill();
        }
    }

    /// Bit position in `data` of the next unread bit.
    fn bit_pos(&self) -> usize {
        let bits = Self::SHIFT - 1 - self.value.trailing_zeros();
        self.pos * 8 - bits as usize
    }

    /// Decodes a single binary decision (`0` or `1`) using `ctx` (ITU-T H.264 9.3.3.2.1).
    ///
    /// Branch-free on the decoded value, which is hard to predict: the LPS case is selected
    /// with masks and the renormalisation shift may be zero.
    #[inline(always)]
    pub fn decode_decision(&mut self, ctx: &mut CabacContext) -> u8 {
        let s = ctx.0 as usize;
        let r_lps = DEC_TAB[DEC_LPS + (((self.range as usize & 0xC0) << 1) | s)] as u32;
        let range = self.range - r_lps;
        let scaled = (range as u64) << Self::SHIFT;
        let lps = self.value >= scaled;
        let mask = (lps as u64).wrapping_neg();
        self.value -= scaled & mask;
        let range = if lps { r_lps } else { range };
        // An LPS complements the index, which flips its low bit from valMPS to the bin.
        let s = s ^ (mask as usize & 0xFF);
        ctx.0 = DEC_TAB[DEC_NEXT + s];
        // range is at least 6 here; one shift restores 256..=511.
        let n = DEC_TAB[range as usize & 511] as u32;
        self.range = range << n;
        self.consume(n);
        (s & 1) as u8
    }

    /// Decodes an equiprobable bypass bin (`0` or `1`, ITU-T H.264 9.3.3.2.3).
    #[inline(always)]
    pub fn decode_bypass(&mut self) -> u8 {
        self.consume(1);
        let scaled = (self.range as u64) << Self::SHIFT;
        if self.value >= scaled {
            self.value -= scaled;
            1
        } else {
            0
        }
    }

    /// Decodes a terminate bin (`0` or `1`, ITU-T H.264 9.3.3.2.4).
    #[inline]
    pub fn decode_terminate(&mut self) -> u8 {
        self.range -= 2;
        if self.value >= (self.range as u64) << Self::SHIFT {
            1
        } else if self.range < 256 {
            // range is at least 254: a single shift renormalises it.
            self.range <<= 1;
            self.consume(1);
            0
        } else {
            0
        }
    }

    /// Decodes `mb_skip_flag` in a P-slice (`ctx 11..13`, where `cond_a / cond_b = 1` when neighbor is available and NOT skipped).
    #[inline]
    pub fn decode_p_skip(&mut self, ctxs: &mut [CabacContext], cond_a: u8, cond_b: u8) -> bool {
        let ctx_idx = 11 + ((cond_a + cond_b) as usize);
        self.decode_decision(&mut ctxs[ctx_idx]) != 0
    }

    /// Decodes `mb_skip_flag` in a B-slice (`ctx 24..26`, where `cond_a / cond_b = 1` when neighbor is available and NOT skipped).
    #[inline]
    pub fn decode_b_skip(&mut self, ctxs: &mut [CabacContext], cond_a: u8, cond_b: u8) -> bool {
        let ctx_idx = 24 + ((cond_a + cond_b) as usize);
        self.decode_decision(&mut ctxs[ctx_idx]) != 0
    }

    /// Reads `dst.len()` raw `I_PCM` sample bytes from the byte-aligned slice payload after `decode_terminate() == 1`
    /// and re-initializes the CABAC arithmetic decoding engine (ITU-T H.264 9.3.1.2).
    pub fn align_for_pcm(&mut self, dst: &mut [u8]) -> Result<()> {
        // The encoder's flush after the terminating bin writes exactly as many bits as the
        // decoder has read (its 9-bit initial window plus one per renormalisation shift), so the
        // PCM alignment bits start at the next unread bit.
        let pcm_start = self.bit_pos().div_ceil(8);
        let pcm_end = pcm_start + dst.len();
        if pcm_end > self.data.len() {
            return Err(RagdollError::BitstreamEndOfData);
        }
        dst.copy_from_slice(&self.data[pcm_start..pcm_end]);
        self.pos = pcm_end;
        self.start();
        Ok(())
    }

    /// Decodes an Intra `mb_type` (`0 = I_NxN`, `1..=24 = I_16x16`, `25 = I_PCM`) with `ctx_base` (`3`, `17`, or `32`).
    pub fn decode_intra_mb_type(
        &mut self,
        ctxs: &mut [CabacContext],
        ctx_base: usize,
        cond_a: u8,
        cond_b: u8,
    ) -> u32 {
        let is_i_slice = ctx_base == 3;
        let c0 = if is_i_slice {
            3 + ((cond_a + cond_b) as usize)
        } else {
            ctx_base
        };
        if self.decode_decision(&mut ctxs[c0]) == 0 {
            return 0;
        }
        if self.decode_terminate() != 0 {
            return 25;
        }
        let (cbp_luma_nz, cbp_chroma, luma_mode) = if is_i_slice {
            let b1 = self.decode_decision(&mut ctxs[6]) as u32;
            let b2 = self.decode_decision(&mut ctxs[7]);
            let cbp_c = if b2 == 0 {
                0
            } else if self.decode_decision(&mut ctxs[8]) == 0 {
                1
            } else {
                2
            };
            let b4 = self.decode_decision(&mut ctxs[9]) as u32;
            let b5 = self.decode_decision(&mut ctxs[10]) as u32;
            (b1, cbp_c, (b4 << 1) | b5)
        } else {
            let b1 = self.decode_decision(&mut ctxs[ctx_base + 1]) as u32;
            let b2 = self.decode_decision(&mut ctxs[ctx_base + 2]);
            let cbp_c = if b2 == 0 {
                0
            } else if self.decode_decision(&mut ctxs[ctx_base + 2]) == 0 {
                1
            } else {
                2
            };
            let b4 = self.decode_decision(&mut ctxs[ctx_base + 3]) as u32;
            let b5 = self.decode_decision(&mut ctxs[ctx_base + 3]) as u32;
            (b1, cbp_c, (b4 << 1) | b5)
        };
        1 + luma_mode + 4 * cbp_chroma + 12 * cbp_luma_nz
    }

    /// Decodes a P-slice `mb_type` (`0 = P_L0_16x16`, `1 = 16x8`, `2 = 8x16`, `3 = P_8x8`, `5..=30 = Intra`).
    pub fn decode_p_mb_type(&mut self, ctxs: &mut [CabacContext]) -> u32 {
        if self.decode_decision(&mut ctxs[14]) != 0 {
            return 5 + self.decode_intra_mb_type(ctxs, 17, 0, 0);
        }
        if self.decode_decision(&mut ctxs[15]) == 0 {
            if self.decode_decision(&mut ctxs[16]) == 0 {
                0 // P_L0_16x16
            } else {
                3 // P_8x8
            }
        } else if self.decode_decision(&mut ctxs[17]) == 0 {
            2 // P_L0_L0_8x16
        } else {
            1 // P_L0_L0_16x8
        }
    }

    /// Decodes a B-slice `mb_type` (`0 = B_Direct_16x16`, `1..=22 = B inter`, `23..=48 = Intra`).
    pub fn decode_b_mb_type(&mut self, ctxs: &mut [CabacContext], cond_a: u8, cond_b: u8) -> u32 {
        let c0 = 27 + ((cond_a + cond_b) as usize);
        if self.decode_decision(&mut ctxs[c0]) == 0 {
            return 0; // B_Direct_16x16
        }
        if self.decode_decision(&mut ctxs[30]) == 0 {
            return 1 + (self.decode_decision(&mut ctxs[32]) as u32);
        }
        if self.decode_decision(&mut ctxs[31]) == 0 {
            let b3 = self.decode_decision(&mut ctxs[32]) as u32;
            let b4 = self.decode_decision(&mut ctxs[32]) as u32;
            let b5 = self.decode_decision(&mut ctxs[32]) as u32;
            return 3 + (b3 << 2) + (b4 << 1) + b5;
        }
        if self.decode_decision(&mut ctxs[32]) == 0 {
            let b4 = self.decode_decision(&mut ctxs[32]) as u32;
            let b5 = self.decode_decision(&mut ctxs[32]) as u32;
            let b6 = self.decode_decision(&mut ctxs[32]) as u32;
            return 11 + (b4 << 2) + (b5 << 1) + b6;
        }
        if self.decode_decision(&mut ctxs[32]) == 0 {
            if self.decode_decision(&mut ctxs[32]) == 0 {
                return 19 + (self.decode_decision(&mut ctxs[32]) as u32);
            } else {
                return 21 + (self.decode_decision(&mut ctxs[32]) as u32);
            }
        }
        // Intra in B-slice (`ctx_base = 32`, but first bin of intra_mb_type is already the next decision at ctx 32!)
        if self.decode_decision(&mut ctxs[32]) == 0 {
            return 23; // I_NxN in B-slice
        }
        if self.decode_terminate() != 0 {
            return 23 + 25; // I_PCM in B-slice
        }
        let b1 = self.decode_decision(&mut ctxs[33]) as u32;
        let b2 = self.decode_decision(&mut ctxs[34]);
        let cbp_c = if b2 == 0 {
            0
        } else if self.decode_decision(&mut ctxs[34]) == 0 {
            1
        } else {
            2
        };
        let b4 = self.decode_decision(&mut ctxs[35]) as u32;
        let b5 = self.decode_decision(&mut ctxs[35]) as u32;
        let luma_mode = (b4 << 1) | b5;
        23 + 1 + luma_mode + 4 * cbp_c + 12 * b1
    }

    /// Decodes `sub_mb_type` in `P_8x8` (`0..=3`, `ctx 21..23`).
    pub fn decode_p_sub_mb_type(&mut self, ctxs: &mut [CabacContext]) -> u8 {
        if self.decode_decision(&mut ctxs[21]) != 0 {
            return 0; // P_L0_8x8
        }
        if self.decode_decision(&mut ctxs[22]) == 0 {
            1 // P_L0_8x4
        } else if self.decode_decision(&mut ctxs[23]) != 0 {
            2 // P_L0_4x8
        } else {
            3 // P_L0_4x4
        }
    }

    /// Decodes `sub_mb_type` in `B_8x8` (`0..=12`, `ctx 36..39`).
    pub fn decode_b_sub_mb_type(&mut self, ctxs: &mut [CabacContext]) -> u8 {
        if self.decode_decision(&mut ctxs[36]) == 0 {
            return 0; // B_Direct_8x8
        }
        if self.decode_decision(&mut ctxs[37]) == 0 {
            return 1 + self.decode_decision(&mut ctxs[39]);
        }
        if self.decode_decision(&mut ctxs[38]) == 0 {
            let b3 = self.decode_decision(&mut ctxs[39]);
            let b4 = self.decode_decision(&mut ctxs[39]);
            return 3 + (b3 << 1) + b4;
        }
        if self.decode_decision(&mut ctxs[39]) == 0 {
            let b4 = self.decode_decision(&mut ctxs[39]);
            let b5 = self.decode_decision(&mut ctxs[39]);
            7 + (b4 << 1) + b5
        } else {
            11 + self.decode_decision(&mut ctxs[39])
        }
    }

    /// Decodes `prev_intra4x4_pred_mode_flag` (`ctx 68`) and `rem_intra4x4_pred_mode` (`ctx 69`).
    pub fn decode_intra4x4_pred_mode(&mut self, ctxs: &mut [CabacContext]) -> (bool, u8) {
        if self.decode_decision(&mut ctxs[68]) != 0 {
            (true, 0)
        } else {
            let b0 = self.decode_decision(&mut ctxs[69]);
            let b1 = self.decode_decision(&mut ctxs[69]);
            let b2 = self.decode_decision(&mut ctxs[69]);
            (false, b0 | (b1 << 1) | (b2 << 2))
        }
    }

    /// Decodes `intra_chroma_pred_mode` (`0..=3`, `ctx 64..67`).
    pub fn decode_chroma_pred_mode(
        &mut self,
        ctxs: &mut [CabacContext],
        cond_a: u8,
        cond_b: u8,
    ) -> u8 {
        let c0 = 64 + ((cond_a + cond_b) as usize);
        if self.decode_decision(&mut ctxs[c0]) == 0 {
            0
        } else if self.decode_decision(&mut ctxs[67]) == 0 {
            1
        } else if self.decode_decision(&mut ctxs[67]) == 0 {
            2
        } else {
            3
        }
    }

    /// Decodes 1 bit of `coded_block_pattern` luma (`ctx 73..76`).
    #[inline]
    pub fn decode_cbp_luma_bit(&mut self, ctxs: &mut [CabacContext], cond_a: u8, cond_b: u8) -> u8 {
        let ctx_idx = 73 + ((cond_a + 2 * cond_b) as usize);
        self.decode_decision(&mut ctxs[ctx_idx])
    }

    /// Decodes `coded_block_pattern` chroma (`0..=2`, `ctx 77..84`).
    pub fn decode_cbp_chroma(
        &mut self,
        ctxs: &mut [CabacContext],
        chroma_a: u8,
        chroma_b: u8,
    ) -> u8 {
        let ca0 = usize::from(chroma_a != 0);
        let cb0 = usize::from(chroma_b != 0);
        if self.decode_decision(&mut ctxs[77 + ca0 + 2 * cb0]) == 0 {
            0
        } else {
            let ca1 = usize::from(chroma_a == 2);
            let cb1 = usize::from(chroma_b == 2);
            if self.decode_decision(&mut ctxs[81 + ca1 + 2 * cb1]) == 0 {
                1
            } else {
                2
            }
        }
    }

    /// Decodes `mb_qp_delta` (`ctx 60..63`).
    pub fn decode_mb_qp_delta(&mut self, ctxs: &mut [CabacContext], prev_nz: u8) -> i32 {
        let c0 = 60 + usize::from(prev_nz != 0);
        if self.decode_decision(&mut ctxs[c0]) == 0 {
            return 0;
        }
        let mut code = 1i32;
        if self.decode_decision(&mut ctxs[62]) != 0 {
            code += 1;
            while code < 104 && self.decode_decision(&mut ctxs[63]) != 0 {
                code += 1;
            }
        }
        if (code & 1) != 0 {
            (code + 1) >> 1
        } else {
            -(code >> 1)
        }
    }

    /// Decodes `ref_idx_l0` / `ref_idx_l1` (`ctx 54..59`).
    pub fn decode_ref_idx(&mut self, ctxs: &mut [CabacContext], cond_a: u8, cond_b: u8) -> u8 {
        let c0 = 54 + ((cond_a + 2 * cond_b) as usize);
        if self.decode_decision(&mut ctxs[c0]) == 0 {
            return 0;
        }
        let mut idx = 1u8;
        if self.decode_decision(&mut ctxs[58]) != 0 {
            idx += 1;
            while idx < 32 && self.decode_decision(&mut ctxs[59]) != 0 {
                idx += 1;
            }
        }
        idx
    }

    /// Decodes `mvd_l0[comp]` or `mvd_l1[comp]` (`comp = 0` for x, `1` for y; `ctx 40..53`).
    pub fn decode_mvd(&mut self, ctxs: &mut [CabacContext], comp: usize, abs_sum: u32) -> i16 {
        let base = if comp == 0 { 40 } else { 47 };
        let inc0 = if abs_sum < 3 {
            0
        } else if abs_sum <= 32 {
            1
        } else {
            2
        };
        if self.decode_decision(&mut ctxs[base + inc0]) == 0 {
            return 0;
        }
        let mut abs_v = 1u32;
        while abs_v < 9 {
            let c_idx = base + 3 + (abs_v as usize - 1).min(3);
            if self.decode_decision(&mut ctxs[c_idx]) == 0 {
                break;
            }
            abs_v += 1;
        }
        if abs_v == 9 {
            let mut k = 3u32;
            while k < 24 && self.decode_bypass() != 0 {
                abs_v += 1 << k;
                k += 1;
            }
            let mut rem = 0u32;
            for _ in 0..k {
                rem = (rem << 1) | (self.decode_bypass() as u32);
            }
            abs_v += rem;
        }
        let sign = self.decode_bypass() != 0;
        let clamped = abs_v.min(32767) as i16;
        if sign { -clamped } else { clamped }
    }

    /// Decodes a zig-zag scanned residual block in CABAC category `cat` (`0..=5`) into `dst`.
    /// Returns `(coded_block_flag, num_nonzero_coeffs)`.
    pub fn decode_residual_block_cat(
        &mut self,
        ctxs: &mut [CabacContext],
        cat: usize,
        cbf_cond: u8,
        dst: &mut [i16],
    ) -> (u8, usize) {
        self.decode_residual_block(ctxs, cat, cbf_cond, dst, false)
    }

    /// [`Self::decode_residual_block_cat`] for frame (`field = false`) or field-coded macroblocks,
    /// which use their own significance-map contexts (ctxIdxOffset 277/338, 436/451).
    pub fn decode_residual_block(
        &mut self,
        ctxs: &mut [CabacContext],
        cat: usize,
        cbf_cond: u8,
        dst: &mut [i16],
        field: bool,
    ) -> (u8, usize) {
        dst.fill(0);
        let mut c = ResidualCoeffs::new();
        let n = self.decode_residual_coeffs(ctxs, cat, cbf_cond, dst.len(), field, &mut c);
        for k in 0..n {
            dst[c.pos[k] as usize] = c.level[k];
        }
        ((n > 0) as u8, n)
    }

    /// Decodes a residual block of `max_coeff` (`1..=64`) coefficients as its nonzero levels and
    /// their scan positions in `out`, returning how many there are (`0` when `coded_block_flag`
    /// is `0`). The other positions are zero.
    pub fn decode_residual_coeffs(
        &mut self,
        ctxs: &mut [CabacContext],
        cat: usize,
        cbf_cond: u8,
        max_coeff: usize,
        field: bool,
        out: &mut ResidualCoeffs,
    ) -> usize {
        // On a local copy the engine state stays in registers across the block.
        let mut d = self.clone();
        let n = d.residual_coeffs(ctxs, cat, cbf_cond, max_coeff, field, out);
        *self = d;
        n
    }

    #[inline(always)]
    fn residual_coeffs(
        &mut self,
        ctxs: &mut [CabacContext],
        cat: usize,
        cbf_cond: u8,
        max_coeff: usize,
        field: bool,
        out: &mut ResidualCoeffs,
    ) -> usize {
        const CBF_BASE: [usize; 5] = [85, 89, 93, 97, 101];
        const SIG_BASE: [[usize; 6]; 2] = [
            [105, 120, 134, 149, 152, 402],
            [277, 292, 306, 321, 324, 436],
        ];
        const LAST_BASE: [[usize; 6]; 2] = [
            [166, 181, 195, 210, 213, 417],
            [338, 353, 367, 382, 385, 451],
        ];
        const LVL_BASE: [usize; 6] = [227, 237, 247, 257, 266, 426];
        let ctxs = &mut ctxs[..NUM_CABAC_CONTEXTS];
        let max_coeff = max_coeff.clamp(1, 64);
        if cat < 5 {
            let cbf_ctx = CBF_BASE[cat] + (cbf_cond as usize);
            if self.decode_decision(&mut ctxs[cbf_ctx]) == 0 {
                return 0;
            }
        }

        let sig_base = SIG_BASE[field as usize][cat];
        let last_base = LAST_BASE[field as usize][cat];
        let lvl_base = LVL_BASE[cat];

        let mut n = 0usize;
        let mut ended = false;
        if cat == 5 {
            let sig_8x8 = if field {
                &SIG_COEFF_OFFSET_8X8_FIELD
            } else {
                &SIG_COEFF_OFFSET_8X8
            };
            for i in 0..max_coeff - 1 {
                if self.decode_decision(&mut ctxs[sig_base + sig_8x8[i] as usize]) != 0 {
                    out.pos[n] = i as u8;
                    n += 1;
                    let last_off = LAST_COEFF_OFFSET_8X8[i] as usize;
                    if self.decode_decision(&mut ctxs[last_base + last_off]) != 0 {
                        ended = true;
                        break;
                    }
                }
            }
        } else {
            // Up to 15 significance and last contexts each, in disjoint ranges.
            let (lo, hi) = ctxs.split_at_mut(last_base);
            let sig: &mut [CabacContext; 15] = (&mut lo[sig_base..sig_base + 15])
                .try_into()
                .expect("15 contexts");
            let last: &mut [CabacContext; 15] = (&mut hi[..15]).try_into().expect("15 contexts");
            for i in 0..max_coeff.min(16) - 1 {
                if self.decode_decision(&mut sig[i]) != 0 {
                    out.pos[n & 63] = i as u8;
                    n += 1;
                    if self.decode_decision(&mut last[i]) != 0 {
                        ended = true;
                        break;
                    }
                }
            }
        }
        if !ended {
            out.pos[n] = (max_coeff - 1) as u8;
            n += 1;
        }

        // Level contexts by "node" (FFmpeg's node_ctx): the count of levels equal to 1 so far
        // (0..=3) while none exceeded 1, else 4 + the count of levels above 1 (9.3.3.1.3).
        const LEVEL1_CTX: [u8; 8] = [1, 2, 3, 4, 0, 0, 0, 0];
        const LEVEL_GT1_CTX: [[u8; 8]; 2] = [[5, 5, 5, 5, 6, 7, 8, 9], [5, 5, 5, 5, 6, 7, 8, 8]];
        const NEXT_NODE: [[u8; 8]; 2] = [[1, 2, 3, 3, 4, 5, 6, 7], [4, 4, 4, 4, 5, 6, 7, 7]];
        // The 10 level contexts (16 taken so that a masked index needs no bounds check).
        let lvl: &mut [CabacContext; 16] = (&mut ctxs[lvl_base..lvl_base + 16])
            .try_into()
            .expect("16 contexts");
        let gt1_ctx = &LEVEL_GT1_CTX[(cat == 3) as usize];
        let mut node = 0usize;
        for k in (0..n).rev() {
            let val = if self.decode_decision(&mut lvl[LEVEL1_CTX[node] as usize & 15]) == 0 {
                node = NEXT_NODE[0][node] as usize & 7;
                1
            } else {
                let c1 = &mut lvl[gt1_ctx[node] as usize & 15];
                let mut v = 2u32;
                while v < 15 && self.decode_decision(c1) != 0 {
                    v += 1;
                }
                if v == 15 {
                    let mut k = 0u32;
                    while k < 24 && self.decode_bypass() != 0 {
                        v += 1 << k;
                        k += 1;
                    }
                    let mut rem = 0u32;
                    for _ in 0..k {
                        rem = (rem << 1) | (self.decode_bypass() as u32);
                    }
                    v += rem;
                }
                node = NEXT_NODE[1][node] as usize & 7;
                v.min(32767) as i16
            };
            out.level[k & 63] = if self.decode_bypass() != 0 { -val } else { val };
        }
        n
    }
}

/// The nonzero coefficients of a residual block: `level[k]` at scan position `pos[k]`.
#[derive(Clone, Debug)]
pub struct ResidualCoeffs {
    pub pos: [u8; 64],
    pub level: [i16; 64],
}

impl ResidualCoeffs {
    pub fn new() -> Self {
        Self {
            pos: [0; 64],
            level: [0; 64],
        }
    }
}

impl Default for ResidualCoeffs {
    fn default() -> Self {
        Self::new()
    }
}
